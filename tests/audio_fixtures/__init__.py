"""Audio regression fixtures (Phase 4-2).

Provenance
----------
* ``ref_voice_a.wav`` / ``ref_voice_b.wav`` are **synthetic** 8 s, 24 kHz mono
  PCM-16 clips produced by :mod:`tests.audio_fixtures.generate_references`
  (deterministic numpy synthesis: harmonic glottal source + formant resonances +
  pitch contour). No third-party or copyrighted audio is committed.
* ``repo_voice_a`` / ``repo_voice_b`` are the pre-existing repository e2e
  fixtures ``tests/test-data/samples/wanda4.wav`` / ``wanda5.wav`` (real
  speech, committed before this harness). ``en_wanda4`` in :data:`TEXTS` is
  wanda4's Whisper-tiny transcript, used as the reference for the
  voice-conversion intelligibility (WER) gate.
* ``ref_voice_de.wav`` is an **optional, user-provided** reference for the
  native-accent German case (``chatterbox_multilingual/tts_de_native``). It is
  not committed: a short self-recorded German speech clip works. Until it
  exists the case is skipped with one log line and excluded from metrics — see
  :func:`reference_available`.
* Texts are short, punctuation-normalised English sentences (plus one German
  sentence for the multilingual family) so tokenisation is stable across runs.

VAD detectability of the synthetic clips (2026-11-09)
-----------------------------------------------------
``voice_a`` / ``voice_b`` are voiced, formant-shaped *tones*, not speech:
Silero VAD at its 16 kHz rate returns **zero** speech segments for both
(measured with ``get_speech_timestamps``), while ``repo_voice_a`` /
``repo_voice_b`` return 1–2. Any pipeline whose clone conditioning is carried
through the VAD step — the OpenVoice ``vad → embed`` pipelines — therefore
cannot use a synthetic clip as the reference: the tone-converter encoder is
handed an empty segment list and fails. Use ``repo_voice_a`` /
``repo_voice_b`` for those paths (see :data:`VAD_UNDETECTABLE_CLIPS`). The
synthetic clips stay valid for non-VAD conditioners (Chatterbox
``prepare_conditionals``) and for VoiceFixer restoration, and their bytes must
not change: other axes pin their output.

The harness compares *two configurations of the current build* (fp32 vs fp16,
deduplicated vs duplicated); it never stores golden audio, because bit-exact
output across torch versions is unrealistic.
"""

from __future__ import annotations

import base64
import functools
import io
import os

import numpy as np
import soundfile as sf

FIXTURE_DIR = os.path.dirname(__file__)
_REPO_SAMPLES = os.path.normpath(os.path.join(FIXTURE_DIR, "..", "test-data", "samples"))

#: Reference clips available to the harness, by logical name.
#:
#: ``voice_a`` / ``voice_b`` are the synthetic clips generated by
#: ``generate_references.py``. ``repo_voice_a`` / ``repo_voice_b`` are the
#: pre-existing repository e2e fixtures (``tests/test-data/samples``) — they are
#: real speech, which the Whisper-VAD-driven toolchains (OpenVoice, Harmony
#: Speech) require; synthetic vowel-like audio is not detected as speech.
REFERENCE_CLIPS = {
    "voice_a": os.path.join(FIXTURE_DIR, "ref_voice_a.wav"),
    "voice_b": os.path.join(FIXTURE_DIR, "ref_voice_b.wav"),
    "repo_voice_a": os.path.join(_REPO_SAMPLES, "wanda4.wav"),
    "repo_voice_b": os.path.join(_REPO_SAMPLES, "wanda5.wav"),
    # Optional: not committed (user-provided German speech). The harness skips
    # the native-accent German case while this file is absent.
    "repo_voice_de": os.path.join(FIXTURE_DIR, "ref_voice_de.wav"),
}

#: Reference clips Silero VAD cannot detect as speech (verified 2026-11-09).
#:
#: The two synthetic clips are voiced tones with formant shaping, which is
#: enough for a direct embedding conditioner but **not** speech for the VAD: at
#: 16 kHz ``get_speech_timestamps`` returns ``[]`` for both, while the real
#: repository clips return one or two segments. A pipeline that routes the
#: reference through its VAD step (OpenVoice ``vad → embed``) then hands the
#: tone-converter encoder an empty segment list; the engine now raises
#: ``ValueError: reference clip contains no detectable speech (VAD segments
#: empty)`` instead of ``stack expects a non-empty TensorList``. Case authors
#: must use ``repo_voice_a`` / ``repo_voice_b`` for those paths.
#:
#: Do **not** regenerate these clips to "fix" detectability: other axes
#: (VoiceFixer restoration, Chatterbox timbre porting) pin their bytes.
VAD_UNDETECTABLE_CLIPS = frozenset({"voice_a", "voice_b"})

#: Fixed texts per family. Keep them short (a few seconds of speech) so a full
#: fp32-vs-fp16 sweep stays a coffee break rather than an afternoon.
TEXTS = {
    "en_short": "The quick brown fox jumps over the lazy dog near the river bank.",
    "en_numbers": "In nineteen eighty four the engine measured exactly nine models.",
    "de_short": "Der schnelle braune Fuchs springt ueber den faulen Hund.",
    "zh_short": "这是一个语音合成回归测试。",
    # Source transcript for the voice-conversion intelligibility gate. wanda4
    # (``repo_voice_a``) is a 3.6 s real-speech clip; this is its faster-
    # whisper-tiny transcription, not an invented sentence.
    "en_wanda4": "It's time to go home.",
    # Mixed-length set for the `batching:1-vs-N` axis: one long, one medium and
    # two short sentences so a padded batch really mixes lengths (and the
    # length-similar sub-batcher has something to do).
    "batch_1": "Hi.",
    "batch_2": "The engine speaks clearly.",
    "batch_3": "When the quick brown fox jumps over the lazy dog the river bank is very quiet.",
    "batch_4": "Thank you very much.",
}


#: Families that sample (stochastic) and therefore need distribution-robust
#: metrics instead of sample-exact comparison. Deterministic families are
#: compared with waveform correlation.
FAMILY_KIND = {
    "harmonyspeech": "deterministic",
    "voicefixer": "deterministic",
    "kittentts": "deterministic",
    "openvoice_v1": "stochastic",
    "openvoice_v2": "stochastic",
    "melotts": "stochastic",
    "chatterbox": "stochastic",
    "chatterbox_turbo": "stochastic",
    "chatterbox_multilingual": "stochastic",
    "chatterbox_vc": "stochastic",
}


def reference_available(name: str) -> bool:
    """Whether a logical reference clip exists on disk.

    Optional fixtures (currently ``repo_voice_de``) are excluded from the
    harness metrics while their file is absent instead of failing the run.
    """
    path = REFERENCE_CLIPS.get(name)
    return bool(path) and os.path.isfile(path)


def vad_detectable_reference(name: str) -> bool:
    """Whether Silero VAD detects speech in ``name`` (see :data:`VAD_UNDETECTABLE_CLIPS`)."""
    return name not in VAD_UNDETECTABLE_CLIPS


def reference_wav_b64(name: str = "voice_a") -> str:
    """Return a reference clip as base64 (the API's JSON audio encoding)."""
    with open(REFERENCE_CLIPS[name], "rb") as handle:
        return base64.b64encode(handle.read()).decode("ascii")


def reference_duration_seconds(name: str = "voice_a") -> float:
    info = sf.info(REFERENCE_CLIPS[name])
    return info.frames / float(info.samplerate)


@functools.lru_cache(maxsize=4)
def tiny_wav_bytes(sample_rate: int = 16000, seconds: float = 0.25) -> bytes:
    """Return a tiny mono PCM-16 WAV (default 250 ms at 16 kHz)."""
    t = np.arange(int(sample_rate * seconds)) / sample_rate
    waveform = (0.2 * np.sin(2 * np.pi * 440 * t)).astype("float32")
    buffer = io.BytesIO()
    sf.write(buffer, waveform, sample_rate, format="WAV", subtype="PCM_16")
    return buffer.getvalue()


@functools.lru_cache(maxsize=4)
def tiny_wav_b64(sample_rate: int = 16000, seconds: float = 0.25) -> str:
    return base64.b64encode(tiny_wav_bytes(sample_rate, seconds)).decode("ascii")


