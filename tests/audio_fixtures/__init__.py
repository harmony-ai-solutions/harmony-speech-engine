"""Audio regression fixtures (Phase 4-2).

Provenance
----------
* ``ref_voice_a.wav`` / ``ref_voice_b.wav`` are **synthetic** 8 s, 24 kHz mono
  PCM-16 clips produced by :mod:`tests.audio_fixtures.generate_references`
  (deterministic numpy synthesis: harmonic glottal source + formant resonances +
  pitch contour). No third-party or copyrighted audio is committed.
* Texts are short, punctuation-normalised English sentences (plus one German
  sentence for the multilingual family) so tokenisation is stable across runs.

The harness compares *two configurations of the current build* (fp32 vs fp16,
deduplicated vs duplicated); it never stores golden audio, because bit-exact
output across torch versions is unrealistic.
"""

from __future__ import annotations

import base64
import functools
import io
import os

import numpy as np
import soundfile as sf

FIXTURE_DIR = os.path.dirname(__file__)
_REPO_SAMPLES = os.path.normpath(os.path.join(FIXTURE_DIR, "..", "test-data", "samples"))

#: Reference clips available to the harness, by logical name.
#:
#: ``voice_a`` / ``voice_b`` are the synthetic clips generated by
#: ``generate_references.py``. ``repo_voice_a`` / ``repo_voice_b`` are the
#: pre-existing repository e2e fixtures (``tests/test-data/samples``) — they are
#: real speech, which the Whisper-VAD-driven toolchains (OpenVoice, Harmony
#: Speech) require; synthetic vowel-like audio is not detected as speech.
REFERENCE_CLIPS = {
    "voice_a": os.path.join(FIXTURE_DIR, "ref_voice_a.wav"),
    "voice_b": os.path.join(FIXTURE_DIR, "ref_voice_b.wav"),
    "repo_voice_a": os.path.join(_REPO_SAMPLES, "wanda4.wav"),
    "repo_voice_b": os.path.join(_REPO_SAMPLES, "wanda5.wav"),
}

#: Fixed texts per family. Keep them short (a few seconds of speech) so a full
#: fp32-vs-fp16 sweep stays a coffee break rather than an afternoon.
TEXTS = {
    "en_short": "The quick brown fox jumps over the lazy dog near the river bank.",
    "en_numbers": "In nineteen eighty four the engine measured exactly nine models.",
    "de_short": "Der schnelle braune Fuchs springt ueber den faulen Hund.",
    "zh_short": "这是一个语音合成回归测试。",
}

#: Families that sample (stochastic) and therefore need distribution-robust
#: metrics instead of sample-exact comparison. Deterministic families are
#: compared with waveform correlation.
FAMILY_KIND = {
    "harmonyspeech": "deterministic",
    "voicefixer": "deterministic",
    "kittentts": "deterministic",
    "openvoice_v1": "stochastic",
    "openvoice_v2": "stochastic",
    "melotts": "stochastic",
    "chatterbox": "stochastic",
    "chatterbox_turbo": "stochastic",
    "chatterbox_multilingual": "stochastic",
    "chatterbox_vc": "stochastic",
}


def reference_wav_b64(name: str = "voice_a") -> str:
    """Return a reference clip as base64 (the API's JSON audio encoding)."""
    with open(REFERENCE_CLIPS[name], "rb") as handle:
        return base64.b64encode(handle.read()).decode("ascii")


def reference_duration_seconds(name: str = "voice_a") -> float:
    info = sf.info(REFERENCE_CLIPS[name])
    return info.frames / float(info.samplerate)


@functools.lru_cache(maxsize=4)
def tiny_wav_bytes(sample_rate: int = 16000, seconds: float = 0.25) -> bytes:
    """Return a tiny mono PCM-16 WAV (default 250 ms at 16 kHz)."""
    t = np.arange(int(sample_rate * seconds)) / sample_rate
    waveform = (0.2 * np.sin(2 * np.pi * 440 * t)).astype("float32")
    buffer = io.BytesIO()
    sf.write(buffer, waveform, sample_rate, format="WAV", subtype="PCM_16")
    return buffer.getvalue()


@functools.lru_cache(maxsize=4)
def tiny_wav_b64(sample_rate: int = 16000, seconds: float = 0.25) -> str:
    return base64.b64encode(tiny_wav_bytes(sample_rate, seconds)).decode("ascii")


